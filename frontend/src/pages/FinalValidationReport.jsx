import { useEffect, useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import axios from 'axios';
import { toast, Toaster } from 'react-hot-toast';
import data from '../data/phase9Data.json';
import { PRODUCTS_API_URL } from '../config';

const findCard = (sections, title) => sections.find((s) => s.title === title) || sections[0];

const parseReport = (report) => {
  const text = report?.summary || '';
  const probability = report?.probability ?? null;
  const sections = {};
  text.split(/^##\s+/m).filter(Boolean).forEach((part) => {
    const lines = part.trim().split('\n');
    const title = lines[0].trim();
    const body = lines.slice(1).join('\n').trim();
    if (title && body) sections[title] = body;
  });
  return { probability, sections, text };
};

export default function FinalValidationReport({ uploadedProduct }) {
  const navigate = useNavigate();
  const [storedReport, setStoredReport] = useState(null);
  const [loading, setLoading] = useState(true);

  const product = uploadedProduct;
  const productName = product?.product_name || 'Pulse';
  const audience = product?.target_audience || 'independent professionals';
  const price = product?.price ? `$${product.price}` : '$29 / month';

  useEffect(() => {
    let cancelled = false;
    if (!product?.id) {
      setLoading(false);
      return () => {};
    }
    setLoading(true);
    axios.get(`${PRODUCTS_API_URL}${product.id}/report`)
      .then((response) => {
        if (!cancelled) setStoredReport(response.data?.report || null);
      })
      .catch(() => {
        if (!cancelled) setStoredReport(null);
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => { cancelled = true; };
  }, [product?.id]);

  const parsed = useMemo(() => parseReport(storedReport), [storedReport]);
  const probability = parsed.probability;
  const sections = parsed.sections;
  const riskLevel = storedReport?.risk_level || null;
  const riskScore = storedReport?.risk_score ?? null;
  const riskAnalysis = storedReport?.risk_analysis || '';

  const now = new Date();
  const timeLabel = now.toUTCString().slice(17, 25);
  const dateLabel = now.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  const generatedAt = `${timeLabel} UTC · ${dateLabel}`;

  const decision = data.launchDecision;
  const readiness = probability ?? decision.progress;

  const strengths = sections['Buyer fit'] || findCard(data.swotCards, 'Strengths').details;
  const risks = sections['Risks and assumptions'] || (data.insightSections.find((s) => s.category === 'Objections')?.items || []).join(' ');
  const opportunities = sections['Recommended next tests'] || findCard(data.swotCards, 'Opportunities').details;
  const summary = sections['Validation summary'] || '';

  const handleAction = (label) => {
    if (label === 'Download PDF' || label === 'Print Report') {
      window.print();
      return;
    }
    if (label === 'Share Report') {
      const text = [
        `${productName} validation report`,
        `Launch decision: ${decision.outcome} · Readiness ${readiness}%`,
        `Generated by PersonaForge AI · ${generatedAt}`,
      ].join('\n');
      navigator.clipboard?.writeText(text).then(() => toast.success('Report summary copied to clipboard')).catch(() => toast.error('Clipboard was blocked'));
      return;
    }
    if (label === 'Export JSON') {
      const payload = {
        report: 'PersonaForge AI validation report',
        product: productName,
        probability,
        risk: { level: riskLevel, score: riskScore, analysis: riskAnalysis },
        decision: decision.outcome,
        generatedAt,
        sections,
      };
      const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = 'personaforge-validation-report.json';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
      toast.success('Validation report exported as JSON');
      return;
    }
    if (label === 'Run New Validation') {
      navigate('/upload');
      return;
    }
    if (label === 'Back to Dashboard') {
      navigate('/dashboard');
      return;
    }
    toast('Action queued for the next step');
  };

  return (
    <section className="page fvr">
      <Toaster position="bottom-right" toastOptions={{ style: { background: '#111111', color: '#f8fafc', border: '1px solid rgba(108, 99, 255, 0.35)' } }} />

      <header className="fvr-banner">
        <div className="fvr-banner-title">
          <span className="label">FINAL VALIDATION REPORT</span>
          <h1>{productName}</h1>
          <p>Assessed for launch readiness using the latest brief and evidence from {audience}.</p>
        </div>
        <div className="fvr-banner-meta">
          <div><span>Generated</span><b>{generatedAt}</b></div>
          <div><span>Price</span><b>{price}</b></div>
          <div><span>Readiness</span><b>{loading ? '—' : `${readiness}%`}</b></div>
        </div>
      </header>

      {loading ? (
        <div className="fvr-card"><p>Loading stored validation report…</p></div>
      ) : storedReport && probability != null ? (
        <>
          <div className="fvr-scores">
            <div className="fvr-score"><span className="fvr-score-label">Validation score</span><b style={{ color: '#8b5cf6' }}>{probability}%</b><p>AI success probability from {audience} signals.</p></div>
            <div className="fvr-score"><span className="fvr-score-label">Launch readiness</span><b style={{ color: '#14b8a6' }}>{readiness}%</b><p>Roadmap and execution confidence.</p></div>
            <div className="fvr-score"><span className="fvr-score-label">Report status</span><b style={{ color: '#38bdf8' }}>Stored</b><p>Saved to the PersonaForge database.</p></div>
            <div className="fvr-score"><span className="fvr-score-label">Risk level</span><b style={{ color: riskLevel === 'High' ? '#f87171' : riskLevel === 'Medium' ? '#facc15' : '#4ade80' }}>{riskLevel || '—'}{riskScore != null ? ` · ${riskScore}%` : ''}</b><p>Launch risk assessed during validation.</p></div>
            <div className="fvr-score"><span className="fvr-score-label">Audience</span><b style={{ color: '#f97316', fontSize: '1.4rem' }}>{audience}</b><p>{data.exportFooter.personas}</p></div>
          </div>

          {summary && (
            <div className="fvr-card">
              <h3>Validation summary</h3>
              <p>{summary}</p>
            </div>
          )}

          <div className="fvr-cols">
            <div className="fvr-card fvr-good"><h3>Buyer fit</h3><p>{strengths}</p></div>
            <div className="fvr-card fvr-bad"><h3>Risks &amp; assumptions</h3><p>{risks}</p></div>
          </div>

          {riskAnalysis && (
            <div className="fvr-card fvr-bad"><h3>Risk analysis</h3><p>{riskAnalysis}</p></div>
          )}

          <div className="fvr-card">
            <h3>Recommended next tests</h3>
            <p>{opportunities}</p>
          </div>
        </>
      ) : (
        <>
          <div className="fvr-scores">
            {data.summaryCards.map((card) => (
              <div className="fvr-score" key={card.id}>
                <span className="fvr-score-label">{card.label}</span>
                <b style={{ color: card.accent }}>{card.value}</b>
                <p>{card.detail}</p>
              </div>
            ))}
          </div>
          <div className="fvr-cols">
            <div className="fvr-card fvr-good"><h3>Strengths</h3><p>{findCard(data.swotCards, 'Strengths').explanation}</p><p>{findCard(data.swotCards, 'Strengths').details}</p></div>
            <div className="fvr-card fvr-bad"><h3>Risks &amp; objections</h3><p>{(data.insightSections.find((s) => s.category === 'Objections')?.items || []).join(' ')}</p><p>{findCard(data.swotCards, 'Threats').details}</p></div>
          </div>
          <div className="fvr-card"><h3>Pricing recommendation</h3><p>{data.insightSections.find((s) => s.category === 'Pricing')?.recommendation}</p></div>
        </>
      )}

      <div className="fvr-card fvr-verdict">
        <div className="fvr-verdict-head">
          <div>
            <span className="label">Launch decision</span>
            <h2>{decision.outcome}</h2>
          </div>
          <div className="fvr-verdict-score">
            <b>{loading ? '—' : readiness}%</b>
            <span>readiness</span>
          </div>
        </div>
        <p>{decision.headline}</p>
        <p>{decision.details}</p>
        <div className="fvr-bar"><span style={{ width: `${loading ? 0 : readiness}%` }} /></div>
        <div className="fvr-meta-row">
          <span>Confidence {decision.confidence}%</span>
          <span>Priority {decision.priority}</span>
          <span>{data.exportFooter.personas}</span>
        </div>
        <div className="fvr-timeline">
          {data.launchTimeline.map((step) => (
            <div className={`fvr-step ${step.status}`} key={step.label}>
              <i />
              <span><b>{step.label}</b><small>{step.date}</small></span>
            </div>
          ))}
        </div>
      </div>

      <div className="fvr-actions">
        {data.exportActions.map((action) => (
          <button key={action.label} type="button" className={`fvr-action ${action.variant}`} onClick={() => handleAction(action.label)}>
            {action.label}
          </button>
        ))}
      </div>

      <footer className="fvr-footer">
        <span>{data.exportFooter.generatedBy}</span>
        <span>{generatedAt}</span>
        <span>{data.exportFooter.personas}</span>
        <span>{data.exportFooter.simulationConfidence}</span>
        <span>{data.exportFooter.version}</span>
      </footer>
    </section>
  );
}
