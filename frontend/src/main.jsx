const createSubmissionId = () => (
  typeof crypto !== 'undefined' && crypto.randomUUID
    ? crypto.randomUUID()
    : `product-${Date.now()}-${Math.random().toString(36).slice(2)}`
);
const validationUrl = (productId) => `${PRODUCTS_API_URL}${productId}/validate`;
const formatPrice = (price, currency) => {
  const symbol = currency === 'INR' ? '₹' : '$';
  return `${symbol}${Number(price).toLocaleString('en-IN')}`;
};
const removeProduct = async (product, reload) => {
  if (!product?.id) return;
  if (!window.confirm(`Delete "${product.product_name}"? This cannot be undone.`)) return;
  try {
    await axios.delete(`${PRODUCTS_API_URL}${product.id}`);
    if (reload) await reload();
  } catch (error) {
    window.alert(error.response?.data?.detail || error.message || 'Unable to delete product.');
  }
};
const downloadReport = (report) => {  const title = report.title || 'validation-report';
  const probability = report.probability != null ? `Success probability: ${report.probability}%\n\n` : '';
  const risk = report.risk_level
    ? `Risk level: ${report.risk_level}${report.risk_score != null ? ` (${report.risk_score}%)` : ''}\n\n${report.risk_analysis || ''}`
    : '';
  const content = `${title}\n\n${probability}${risk}\n\n${report.summary || ''}\n\nGenerated by PersonaForge AI`;
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};
const UPLOADED_PRODUCT_KEY = 'uploaded_product';
const PENDING_PRODUCT_KEY = 'pending_product';

const Page = ({ children }) => <section className="page">{children}</section>;

