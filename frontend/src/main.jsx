function Upload({ setUploadedProduct }) {
  const navigate = useNavigate();
  const [form, setForm] = useState({
    product_name: '',
    description: '',
    category: '',
    price: '',
    target_audience: '',
    currency: 'USD',
    product_image: '',
  });
  const [status, setStatus] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  const handleChange = (event) => {
    const { name, value } = event.target;
    setForm((current) => ({
      ...current,
      [name]: name === 'price' ? value.replace(/[^0-9.]/g, '') : value,
    }));
  };

  const handleFileChange = (event) => {
    const file = event.target.files?.[0];
    if (!file) {
      return;
    }
    if (file.size > 2 * 1024 * 1024) {
      setStatus('Please choose an image smaller than 2 MB.');
      event.target.value = '';
      return;
    }

    const reader = new FileReader();
    reader.onload = () => setForm((current) => ({ ...current, product_image: reader.result || '' }));
    reader.readAsDataURL(file);
  };

  const handleSubmit = async () => {
    setStatus('');
    const priceValue = parseFloat(form.price);
    if (
      !form.product_name ||
      !form.description ||
      !form.category ||
      !form.target_audience ||
      Number.isNaN(priceValue) ||
      priceValue <= 0
    ) {
      setStatus('Please fill in all required fields with valid values.');
      return;
    }

    const submission_id = createSubmissionId();
    const payload = {
      ...form,
      price: priceValue,
      submission_id,
    };

    setIsSubmitting(true);

    // If offline, save locally and proceed to processing view
    if (typeof navigator !== 'undefined' && !navigator.onLine) {
      const localProduct = { ...payload, id: submission_id };
      try {
        localStorage.setItem(PENDING_PRODUCT_KEY, JSON.stringify(localProduct));
        localStorage.setItem(UPLOADED_PRODUCT_KEY, JSON.stringify(localProduct));
      } catch (e) {
        // ignore localStorage errors
      }
      setUploadedProduct(localProduct);
      setStatus('You are offline — product saved locally. Proceeding to analysis.');
      setIsSubmitting(false);
      navigate('/processing');
      return;
    }

    try {
      const response = await axios.post(PRODUCTS_API_URL, payload);
      const savedProduct = response.data.product || payload;
      try {
        localStorage.removeItem('pending_product');
        localStorage.setItem(UPLOADED_PRODUCT_KEY, JSON.stringify(savedProduct));
      } catch (e) {}
      setUploadedProduct(savedProduct);
      setStatus(response.data?.message || 'Submitted successfully.');
      navigate('/processing');
    } catch (error) {
      // On failure, fallback to local save so the UI can continue without changing styles
      const localProduct = { ...payload, id: submission_id };
      try {
        localStorage.setItem(PENDING_PRODUCT_KEY, JSON.stringify(localProduct));
        localStorage.setItem(UPLOADED_PRODUCT_KEY, JSON.stringify(localProduct));
        setUploadedProduct(localProduct);
        setStatus('Backend unreachable — product saved locally. Proceeding to analysis.');
        navigate('/processing');
      } catch (e) {
        setStatus(error.response?.data?.detail || error.message || 'Submission failed.');
      }
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <Page>
      <Label>NEW VALIDATION</Label>
      <h1>Give your idea a universe.</h1>
      <p className="sub">Upload your product details to create a stored AI validation report.</p>
      <div className="upload-layout">
        <div className="panel">
          <div className="upload-form">
            <label>
              Product name
              <input
                name="product_name"
                value={form.product_name}
                onChange={handleChange}
                placeholder="Enter product name"
              />
            </label>
            <label>
              Target audience
              <input
                name="target_audience"
                value={form.target_audience}
                onChange={handleChange}
                placeholder="e.g. Freelancers"
              />
            </label>
            <label>
              Category
              <input
                name="category"
                value={form.category}
                onChange={handleChange}
                placeholder="e.g. Finance software"
              />
            </label>
            <label>
              Price
              <input
                type="number"
                step="0.01"
                name="price"
                value={form.price}
                onChange={handleChange}
                placeholder="Enter product price"
              />
            </label>
            <label>
              Currency
              <select name="currency" value={form.currency} onChange={handleChange}>
                <option value="USD">$ US Dollar</option>
                <option value="INR">₹ Indian Rupee</option>
              </select>
            </label>
            <label>
              Description
              <textarea
                name="description"
                value={form.description}
                onChange={handleChange}
                placeholder="Describe your product"
              />
            </label>
            <label>
              Product image
              <input type="file" accept="image/*" onChange={handleFileChange} />
            </label>
            {form.product_image && <p className="image-preview">Image selected for upload.</p>}
            <Button kind="primary" onClick={handleSubmit} disabled={isSubmitting}>
              {isSubmitting ? 'Saving...' : 'Save and validate product'}
            </Button>
            {status && <p className="status">{status}</p>}
          </div>
        </div>
        <aside className="panel checklist">
          <Label>VALIDATION CHECKLIST</Label>
          {(() => {
            const checks = [
              { label: 'Product name', ok: Boolean(form.product_name.trim()) },
              { label: 'Pricing', ok: Number(parseFloat(form.price)) > 0 },
              { label: 'Audience', ok: Boolean(form.target_audience.trim()) },
              { label: 'Description', ok: Boolean(form.description.trim()) },
              { label: 'Screenshot', ok: Boolean(form.product_image) },
            ];
            const done = checks.filter((c) => c.ok).length;
            const pct = Math.round((done / checks.length) * 100);
            const ready = done === checks.length;
            const fillColor = `hsl(${Math.round((pct / 100) * 120)}, 65%, 55%)`;
            return (
              <>
                <div className="circle-wrap">
                  <i
                    className="circle-fill"
                    style={{
                      background: `conic-gradient(${fillColor} ${pct * 3.6}deg, #262626 ${pct * 3.6}deg 360deg)`,
                    }}
                  />
                  <b className="circle" style={{ color: fillColor }}>{pct}%</b>
                </div>
                {checks.map(({ label, ok }) => (
                  <p key={label} className={ok ? '' : 'empty'}>{ok ? '✓' : '✗'} <span>{label}</span></p>
                ))}
                <Label>{ready ? 'READY FOR AI ANALYSIS' : 'COMPLETE ALL FIELDS FOR AI ANALYSIS'}</Label>
              </>
            );
          })()}
        </aside>
      </div>
    </Page>
  );
}

function Products({ setUploadedProduct }) {
  const navigate = useNavigate();
  const [products, setProducts] = useState([]);
  const [status, setStatus] = useState('Loading saved products…');

  const loadProducts = async () => {
    setStatus('Loading saved products…');
    try {
      const response = await axios.get(PRODUCTS_API_URL);
      const saved = response.data.products || [];
      setProducts(saved);
      setStatus(saved.length ? '' : 'No products have been uploaded yet.');
    } catch (error) {
      setStatus(error.response?.data?.detail || 'Unable to load saved products.');
    }
  };

  useEffect(() => { loadProducts(); }, []);

  return (
    <Page>
      <Label>SAVED PRODUCTS</Label>
      <h1>Your submitted product briefs.</h1>
      <p className="sub">These records come directly from your PersonaForge database.</p>
      <Button kind="primary" onClick={() => navigate('/upload')}>Upload a product</Button>
      <Button onClick={loadProducts}>Refresh</Button>
      {status && <p className="status">{status}</p>}
      <div className="persona-grid">
        {products.map((product) => (
          <article className="persona" key={product.id}>
            <b>{product.product_name}</b>
            <small>{product.category} · {formatPrice(product.price, product.currency)}</small>
            <p>{product.description}</p>
            <em>{product.target_audience}</em>
            {product.product_image && <img className="uploaded-preview" src={product.product_image} alt={product.product_name} />}
            <Button onClick={() => { localStorage.setItem(UPLOADED_PRODUCT_KEY, JSON.stringify(product)); setUploadedProduct(product); navigate('/processing'); }}>View product</Button>
            <Button kind="danger" onClick={() => removeProduct(product, loadProducts)}>Remove</Button>
          </article>
        ))}
      </div>
    </Page>
  );
}

function Processing({ uploadedProduct }) {
  const navigate = useNavigate();
  const [localProduct, setLocalProduct] = useState(null);
  const [report, setReport] = useState(null);
  const [validationStatus, setValidationStatus] = useState('');
  const [validationAttempted, setValidationAttempted] = useState(false);

  useEffect(() => {
    if (uploadedProduct) return;
    try {
      const saved = localStorage.getItem(UPLOADED_PRODUCT_KEY);
      const pending = localStorage.getItem('pending_product');
      if (saved) setLocalProduct(JSON.parse(saved));
      else if (pending) setLocalProduct(JSON.parse(pending));
      else navigate('/products');
    } catch (e) {
      navigate('/products');
    }
  }, [navigate, uploadedProduct]);

  const product = uploadedProduct || localProduct;
  useEffect(() => {
    if (!product?.id || report || validationAttempted) return;
    setValidationAttempted(true);
    setValidationStatus('Generating validation report…');
    axios.post(validationUrl(product.id))
      .then((response) => {
        setReport(response.data.report);
        setValidationStatus(response.data.cached ? 'Loaded saved validation report.' : 'Validation report created.');
      })
      .catch((error) => setValidationStatus(error.response?.data?.detail || 'Validation could not be completed. Please try again.'));
  }, [product?.id, report, validationAttempted]);

  return (
    <Page>
      <div className="processing">
        <Label>PRODUCT RECORD</Label>
        <h1>{product ? 'Your product is saved.' : 'Loading product…'}</h1>
        {product && <div className="product-summary">
          <strong>{product.product_name}</strong>
          <p>{product.description}</p>
          <p><em>{product.category} · {product.target_audience} · {formatPrice(product.price, product.currency)}</em></p>
          {product.product_image && <img className="uploaded-preview" src={product.product_image} alt={product.product_name} />}
        </div>}
        {validationStatus && <p className="status">{validationStatus}</p>}
        {report && <article className="panel validation-report">
          <Label>AI VALIDATION REPORT</Label>
          {report.probability != null && <div className="probability-badge"><b>{report.probability}%</b><span>success probability</span></div>}
          {report.risk_level && <div className={`risk-badge risk-${report.risk_level.toLowerCase()}`}><b>{report.risk_level} risk</b><span>{report.risk_score != null ? `${report.risk_score}% · ` : ''}assessed during validation</span></div>}
          <h2>{report.title}</h2>
          <pre>{report.summary}</pre>
          {report.risk_analysis && <>
            <h3>Risk analysis</h3>
            <pre>{report.risk_analysis}</pre>
          </>}
          <Button kind="primary" onClick={() => downloadReport(report)}>Download report</Button>
          <Button kind="violet" onClick={() => navigate('/simulation')}>Run product simulation →</Button>
        </article>}
        <Button kind="primary" onClick={() => navigate('/products')}>View saved products</Button>
        <Button onClick={() => navigate('/upload')}>Upload another product</Button>
      </div>
    </Page>
  );
}

function App() {
  const [uploadedProduct, setUploadedProduct] = useState(null);
  const location = useLocation();

  useEffect(() => {
    let persistedProduct = null;
    try {
      const stored = localStorage.getItem(UPLOADED_PRODUCT_KEY);
      persistedProduct = stored ? JSON.parse(stored) : null;
    } catch (e) {
      persistedProduct = null;
    }

    if (persistedProduct) {
      setUploadedProduct(persistedProduct);
    }

    const syncPendingProduct = async () => {
      if (typeof navigator !== 'undefined' && !navigator.onLine) {
        return;
      }

      let pendingProduct;
      try {
        const pending = localStorage.getItem(PENDING_PRODUCT_KEY);
        pendingProduct = pending ? JSON.parse(pending) : null;
      } catch (e) {
        return;
      }

      if (!pendingProduct) {
        return;
      }

      try {
        const response = await axios.post(PRODUCTS_API_URL, pendingProduct);
        localStorage.removeItem(PENDING_PRODUCT_KEY);
        const savedProduct = response.data.product || pendingProduct;
        localStorage.setItem(UPLOADED_PRODUCT_KEY, JSON.stringify(savedProduct));
        setUploadedProduct(savedProduct);
      } catch (e) {
        // Keep the product queued for the next app load or online event.
      }
    };

    syncPendingProduct();
    window.addEventListener('online', syncPendingProduct);
    return () => window.removeEventListener('online', syncPendingProduct);
  }, []);

  return (
    <ErrorBoundary>
      <Shell>
        <Suspense fallback={<PageLoader />}>
          <AnimatePresence mode="wait">
            <motion.div
              key={location.pathname}
              initial={{ opacity: 0, y: 18, filter: 'blur(6px)' }}
              animate={{ opacity: 1, y: 0, filter: 'blur(0px)' }}
              exit={{ opacity: 0, y: -18, filter: 'blur(6px)' }}
              transition={{ duration: 0.35, ease: [0.22, 1, 0.36, 1] }}
            >
              <Routes location={location}>
                <Route path="*" element={<Navigate to="/persona.html" replace />} />
                <Route path="/workspace" element={<Welcome />} />
                <Route path="/upload" element={<Upload setUploadedProduct={setUploadedProduct} />} />
                <Route path="/processing" element={<Processing uploadedProduct={uploadedProduct} />} />
                <Route path="/products" element={<Products setUploadedProduct={setUploadedProduct} />} />
                <Route path="/simulation" element={<SimulationEngine uploadedProduct={uploadedProduct} />} />
                <Route path="/report" element={<FinalValidationReport uploadedProduct={uploadedProduct} />} />
                <Route path="/dashboard" element={<IntelligenceDashboard />} />
                <Route path="/mission-control" element={<MissionControl />} />
                <Route path="/persona-galaxy" element={<PersonaGalaxy />} />
                <Route path="/persona-generation" element={<PersonaGeneration />} />
              </Routes>
            </motion.div>
          </AnimatePresence>
        </Suspense>
      </Shell>
    </ErrorBoundary>
  );
}

createRoot(document.getElementById('root')).render(
  <BrowserRouter><App /></BrowserRouter>
);
